import { addMedia, addTrack } from './edit';
import { importFiles } from './media';
import { SOUND_STORE, getRecord, putRecord, recordKeys } from './persist';
import { PACK, type PackSound } from './soundpack';
import { SYNTH, renderSynth, type SynthSound } from './soundsynth';
import { store } from './state';
import { button, h, icons, toast } from './util';

type Item = { kind: 'synth'; sound: SynthSound } | { kind: 'pack'; sound: PackSound };

const CATEGORIES: [string, string][] = [
  ['all', 'All'],
  ['nature', 'Nature'],
  ['water', 'Water'],
  ['animals', 'Animals'],
  ['humans', 'People'],
  ['vehicles', 'Vehicles'],
  ['outdoors', 'Outdoors'],
  ['objects', 'Objects'],
];

const MIME: Record<string, string> = { ogg: 'audio/ogg', oga: 'audio/ogg', wav: 'audio/wav', mp3: 'audio/mpeg', flac: 'audio/flac' };

function freeAudioTrack(start: number, duration: number): string | undefined {
  const end = start + duration;
  const free = (id: string): boolean => !store.project.clips.some(c => c.trackId === id && c.start < end && c.start + c.duration > start);
  const found = store.project.tracks.find(t => t.kind === 'audio' && !t.locked && free(t.id));
  if (found) return found.id;
  addTrack('audio');
  return store.project.tracks.filter(t => t.kind === 'audio').pop()?.id;
}

export class SoundLibrary {
  private readonly overlay = h('div', { class: 'overlay sound-overlay hidden' });
  private readonly list = h('div', { class: 'sound-list' });
  private readonly search = h('input', { type: 'search', class: 'text-input', placeholder: 'Search sounds…' });
  private readonly chips = h('div', { class: 'sound-cats' });
  private readonly packStatus = h('span', { class: 'hint grow' });
  private readonly downloadAll: HTMLButtonElement;
  private readonly credits = h('div', { class: 'sound-credits hidden' });
  private readonly synthCache = new Map<string, Blob>();
  private cached = new Set<string>();
  private category = 'all';
  private player: HTMLAudioElement | null = null;
  private playing = '';
  private downloading = false;

  constructor() {
    this.downloadAll = button('Download all recordings', 'Save every recording in this browser so it works offline', () => void this.saveAll(), 'btn small');
    for (const [id, label] of CATEGORIES) {
      this.chips.append(button(label, `Show ${label.toLowerCase()} sounds`, () => {
        this.category = id;
        this.render();
      }, 'chip'));
    }
    this.search.addEventListener('input', () => this.render());
    this.credits.append(
      h('p', { class: 'hint' }, 'Recordings come from Wikimedia Commons and are public domain or CC0, so you can use them in any video without credit. Built-in sounds are generated by Frameforge.'),
      ...PACK.map(p => h('div', { class: 'credit' }, h('a', { href: p.source, target: '_blank', rel: 'noopener' }, p.label), ` — ${p.author} · ${p.license}`)),
    );
    const win = h(
      'div',
      { class: 'sound-window' },
      h('div', { class: 'ie-header' }, h('span', { class: 'ie-brand' }, h('span', { class: 'logo small' }), 'Sound Library'), this.search, button(icons.close, 'Close (Esc)', () => this.close(), 'icon-btn')),
      this.chips,
      this.list,
      this.credits,
      h('div', { class: 'ie-footer' }, this.packStatus, button('Credits', 'Show where the recordings come from', () => this.credits.classList.toggle('hidden'), 'btn small'), this.downloadAll),
    );
    this.overlay.append(win);
    this.overlay.addEventListener('pointerdown', e => {
      if (e.target === this.overlay) this.close();
    });
    window.addEventListener('keydown', e => {
      if (this.overlay.classList.contains('hidden') || e.key !== 'Escape') return;
      e.stopPropagation();
      this.close();
    }, true);
    document.body.append(this.overlay);
  }

  async open(): Promise<void> {
    this.overlay.classList.remove('hidden');
    this.cached = new Set(await recordKeys(SOUND_STORE).catch(() => []));
    this.render();
    this.search.focus();
  }

  private close(): void {
    this.stop();
    this.overlay.classList.add('hidden');
  }

  private items(): Item[] {
    const q = this.search.value.trim().toLowerCase();
    const all: Item[] = [...SYNTH.map(sound => ({ kind: 'synth' as const, sound })), ...PACK.map(sound => ({ kind: 'pack' as const, sound }))];
    return all
      .filter(i => this.category === 'all' || i.sound.cat === this.category)
      .filter(i => !q || i.sound.cat.startsWith(q) || i.sound.label.toLowerCase().split(/[^a-z]+/).some(w => w.startsWith(q)) || (q.includes(' ') && i.sound.label.toLowerCase().includes(q)))
      .sort((a, b) => a.sound.cat.localeCompare(b.sound.cat) || a.sound.label.localeCompare(b.sound.label));
  }

  private render(): void {
    this.chips.querySelectorAll('.chip').forEach((c, i) => c.classList.toggle('on', CATEGORIES[i][0] === this.category));
    const items = this.items();
    this.list.replaceChildren(...(items.length ? items.map(i => this.row(i)) : [h('div', { class: 'empty' }, h('strong', {}, 'No sounds found'), h('span', {}, 'Try another word or category.'))]));
    const saved = PACK.filter(p => this.cached.has(p.id)).length;
    const total = (PACK.reduce((n, p) => n + p.kb, 0) / 1024).toFixed(0);
    this.packStatus.textContent = `${SYNTH.length} built-in sounds always work offline · ${saved} of ${PACK.length} recordings saved offline`;
    this.downloadAll.textContent = saved === PACK.length ? 'All recordings saved' : `Download all recordings (${total} MB)`;
    this.downloadAll.disabled = saved === PACK.length || this.downloading;
  }

  private id(i: Item): string {
    return i.kind === 'synth' ? `synth:${i.sound.id}` : i.sound.id;
  }

  private row(i: Item): HTMLElement {
    const id = this.id(i);
    const tag =
      i.kind === 'synth'
        ? h('span', { class: 'tag built' }, 'Built-in')
        : h(
            'span',
            { class: `tag ${this.cached.has(i.sound.id) ? 'saved' : 'web'}`, title: this.cached.has(i.sound.id) ? 'Real recording, saved for offline use' : 'Real recording, downloads once' },
            this.cached.has(i.sound.id) ? 'Recording ✓' : i.sound.kb >= 1024 ? `Rec · ${(i.sound.kb / 1024).toFixed(1)} MB` : `Rec · ${i.sound.kb} KB`,
          );
    const play = button(this.playing === id ? icons.pause : icons.play, this.playing === id ? 'Stop' : 'Preview', () => void this.preview(i), 'icon-btn boxed');
    const add = button(`${icons.plus}<span>Add</span>`, 'Add to the timeline at the playhead', () => void this.add(i, add), 'btn small primary');
    return h('div', { class: 'sound-row' }, play, h('div', { class: 'sound-name' }, h('strong', {}, i.sound.label), h('span', {}, CATEGORIES.find(c => c[0] === i.sound.cat)?.[1] ?? '', tag)), add);
  }

  private async blob(i: Item): Promise<Blob> {
    if (i.kind === 'synth') {
      let b = this.synthCache.get(i.sound.id);
      if (!b) {
        b = renderSynth(i.sound);
        this.synthCache.set(i.sound.id, b);
      }
      return b;
    }
    const saved = await getRecord(SOUND_STORE, i.sound.id).catch(() => undefined);
    if (saved) return saved;
    const res = await fetch(i.sound.url);
    if (!res.ok) throw new Error(`download failed (${res.status})`);
    const b = new Blob([await res.arrayBuffer()], { type: MIME[i.sound.ext] ?? 'audio/ogg' });
    await putRecord(SOUND_STORE, i.sound.id, b).catch(() => undefined);
    this.cached.add(i.sound.id);
    return b;
  }

  private stop(): void {
    if (this.player) {
      const src = this.player.src;
      this.player.pause();
      this.player.removeAttribute('src');
      this.player.load();
      URL.revokeObjectURL(src);
    }
    this.player = null;
    this.playing = '';
  }

  private async preview(i: Item): Promise<void> {
    const id = this.id(i);
    const again = this.playing === id;
    this.stop();
    if (again) {
      this.render();
      return;
    }
    try {
      this.playing = id;
      this.render();
      const blob = await this.blob(i);
      if (this.playing !== id) return;
      const audio = new Audio(URL.createObjectURL(blob));
      this.player = audio;
      audio.addEventListener('ended', () => {
        if (this.player !== audio) return;
        this.stop();
        this.render();
      });
      await audio.play();
    } catch (e) {
      this.stop();
      toast(`Could not play this sound: ${(e as Error).message}. Recordings need internet the first time.`);
    }
    this.render();
  }

  private async add(i: Item, btn: HTMLButtonElement): Promise<void> {
    btn.disabled = true;
    btn.textContent = 'Adding…';
    try {
      const blob = await this.blob(i);
      const ext = i.kind === 'synth' ? 'wav' : i.sound.ext;
      const [mediaId] = await importFiles([new File([blob], `${i.sound.label}.${ext}`, { type: blob.type })]);
      if (mediaId) {
        addMedia(mediaId, freeAudioTrack(store.ui.playhead, store.media(mediaId)?.duration ?? 1), store.ui.playhead);
        toast(`Added "${i.sound.label}" at the playhead`);
      }
    } catch (e) {
      toast(`Could not add this sound: ${(e as Error).message}. Recordings need internet the first time.`);
    }
    this.render();
  }

  private async saveAll(): Promise<void> {
    this.downloading = true;
    const todo = PACK.filter(p => !this.cached.has(p.id));
    let done = 0;
    let failed = 0;
    for (const sound of todo) {
      this.downloadAll.textContent = `Downloading ${done + 1} of ${todo.length}…`;
      try {
        await this.blob({ kind: 'pack', sound });
      } catch {
        failed++;
      }
      done++;
    }
    this.downloading = false;
    this.render();
    toast(failed ? `${failed} recording${failed > 1 ? 's' : ''} could not be downloaded. Check your connection and try again.` : 'All recordings are saved. The library now works offline.');
  }
}
